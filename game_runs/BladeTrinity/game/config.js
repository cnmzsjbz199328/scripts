  dojo: [
    { key: 'far', scale: 0.677, depth: -100 },
    { key: 'mid', scale: 0.532, depth: -50 },
    { key: 'fore', scale: 0.606, depth: 20 },   // depth > 角色的 10，压在脚上
  ],
  // scale 由 tools/measure-bg.mjs 实测地面线后回填（源图 1920×1080）：
  //   far  石台面中部 y≈891 × 0.534 = 475.8 → 角色站在石台面上，不是台沿外
  //        （最强水平边量到的 856 是台面【后沿】，站那儿等于贴着远景山脚，太靠后）
  //   fore 落叶带中央顶边 y≈860 × 0.542 = 466.1 → FLOOR_Y 上方 10px，同室内套件的接地量
  //   mid  檐廊石阶/栅栏底 y≈887 × 0.537 = 476.3 → 坐在 FLOOR_Y
  //        （中央 60% 量到的 990 是右侧栅栏越界的一小段，中景中央本就留空，取全幅中位）
  // 三层 0.534/0.537/0.542 几乎同比例——这套图彼此协调，不像室内那套 mid 比 far 小 21%
  //
