// 图集格规格（video-sprite 标准，见 assets/sprites/atlases.js）
BT.FRAME_W = 192;
BT.FRAME_H = 208;
// 图集的统一 scale 取了六行最小值（为让最伸展的挥刀/倒地姿势完整入格），
// 角色因此只占格高约 60%，这里放大回格斗游戏该有的体量
BT.SCALE = 1.9;

// 命中框半宽（纹理 26px × SCALE）。刀尖碰到对手躯干边缘即算命中，
// 所以攻击距离 = 当前帧刀长 + 这个半宽。
BT.BODY_HALF_W = 26 * BT.SCALE;

// 角色 x 的【合法区间边界】。命中框半宽就是 26×SCALE（见 _makeFighter 的 setSize/setOffset），
// 所以世界边界钳制之后 x 恒在 [EDGE_X, GAME_W-EDGE_X] = [49.4, 910.6]。
//
// ⚠️ 所有【手动改 x】的地方（互推 / 缩地 / 绕背 / 压边 / 会心贴身）都必须用 _clampX 钳一遍。
// 写越界值不会报错，但 Arcade 的钳制发生在【下一帧】的物理步进：越界位置会先被真的渲染
// 一帧，下一帧才弹回来 —— 隔帧跳变就是墙角抖动的波形（实测 49.4↔42.1↔49.4↔45.75）。
// 曾经这几处各写各的 56，比真实边界内缩 6.6px，既不准也压不住上面那个坑。
BT.EDGE_X = BT.BODY_HALF_W;

// 击退"退得动吗"的判据：上挑滞空约 140ms（vy 90~105 / GRAVITY 1500），其间横向本该
// 走 155×0.14 ≈ 22px。剩余可退空间不足这个数，那一跳就是纯原地的（见 _knockback）。
BT.WALL_ROOM = 26;

// 起跳初速（玩家 loop.js / AI routine.js 的剑气追 共用，必须同值 —— 跳跃高度
// 是对称资源，一边跳得比另一边高，纵向闸门就成了单方面特权）。
//
// ⚠️ 这个数【不是手感旋钮，是躲避判定的参数】。近战命中的纵向闸门是
// _resolveMelee 的 |Δy| ≥ 96，抛物线 h(t)=Vt-(GRAVITY/2)t²，于是：
//     顶点 = V²/(2·GRAVITY)     升过闸门的耗时 = h(t)>96 的小根
// 曾经是 600：顶点只有 120px（对 96 只余 24px），升过闸门要 221ms，800ms 滞空
// 里有 442ms 仍可被打。而平A 的命中窗口起点是 190~400ms（BT.ATTACK.from）——
// 人类反应 200ms + 爬升 221ms = 420ms 才安全，剑神 280ms 的刀必中、水神 190ms
// 更不用说：【反应式起跳在数学上不可能躲开平A】，只有提前 0.25s 预判才行。
// 叠上"腾空禁止架防"（defense.js），按一次跳等于拿 800ms 不能防御换 358ms 打不到，
// 对任何威胁都严格劣于按住 S —— 用户实测"跳跃也避不开伤害"就是这个。
//
// 720 的两个根正好是整数：顶点 172.8px，滞空 960ms，安全区 t∈[0.16,0.80]（640ms/67%），
// 升过闸门只要 160ms —— 落在人类反应 + 剑神 280ms 抬手之内，反应式起跳才第一次成立。
// ⚠️ 再往上调会把滞空推过 1s：不能防御的窗口比躲掉的收益还长，跳跃重新变成净亏。
// 改这个数必须同步 BT.AI_RT.qiEtaMin/Max（那两个数就是从这条抛物线解出来的）。
BT.JUMP_VY = 720;

// ─────────── 背景三层贴图定位 ───────────
// 三张源图（1920×1080）的地面线【互不相同】，提示词里要求的统一 88% 一个都没遵守：
//   far  地板线      y=703 (65.1%)
//   mid  柱础底      y=894 (82.8%)
//   fore 中央木板顶边 y=769 (71.2%)
// 所以不能用同一个缩放对齐三层，每层单独定标：scale = 目标屏幕 y ÷ 源图 y。
//   far  703 × 0.677 = 475.9 → 地板线正好压在 FLOOR_Y
//   mid  894 × 0.532 = 475.6 → 柱础坐在 FLOOR_Y
//   fore 769 × 0.606 = 466.0 → 木板顶边在 FLOOR_Y 上方 10px：盖住脚踝以下与倒地
//        接触点（配合 BT.DOWN_DROP 的下沉），但只吃 10px，不影响看步法
// 三层都是 origin(0.5,0)、贴画布顶、水平居中，超出 960×540 的部分自然裁掉。
//
// ⚠️ mid 的 0.532 小于 far 的 0.677，中景柱子比远景天花板梁小约 21%——透视上是反的。
// 取舍：统一到 0.677 得把 mid 上移 129px，会削掉顶部灯笼一半，那是更显眼的瑕疵。
// 柱子和天花板梁是不同物体，没有可比的参照，实际观感吃得下。
//
// ─────────── 一场一景 ───────────
// 擂台共两场（oppQueue = 另两家流派），每场一套三层背景：
//   第 1 场 dojo    — 室内道场（原设计，保留）
//   第 2 场 outdoor — 雪山之巅露天演武场：远景雪山 / 中景室外道场檐廊 / 近景枫树银杏
// 落叶前景物理层（foregroundPhysics.js）是独立于背景的运行时系统，两场都在，
// 只是室外那场把它开满——枫/橡/银杏三色本来就是照着 outdoor_fore 的树配的。
