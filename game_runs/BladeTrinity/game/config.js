/* BladeTrinity — 全局命名空间与画布常量。必须先于 data.js 加载。 */
window.BT = window.BT || {};

BT.GAME_W = 960;
BT.GAME_H = 540;
BT.FLOOR_Y = 476;
BT.GRAVITY = 1500;

// 图集格规格（video-sprite 标准，见 assets/sprites/atlases.js）
BT.FRAME_W = 192;
BT.FRAME_H = 208;
// 图集的统一 scale 取了六行最小值（为让最伸展的挥刀/倒地姿势完整入格），
// 角色因此只占格高约 60%，这里放大回格斗游戏该有的体量
BT.SCALE = 1.9;

// 命中框半宽（纹理 26px × SCALE）。刀尖碰到对手躯干边缘即算命中，
// 所以攻击距离 = 当前帧刀长 + 这个半宽。
BT.BODY_HALF_W = 26 * BT.SCALE;

// 角色 x 的【合法区间边界】。命中框半宽就是 26×SCALE（见 _makeFighter 的 setSize/setOffset），
// 所以世界边界钳制之后 x 恒在 [EDGE_X, GAME_W-EDGE_X] = [49.4, 910.6]。
//
// ⚠️ 所有【手动改 x】的地方（互推 / 缩地 / 绕背 / 压边 / 会心贴身）都必须用 _clampX 钳一遍。
// 写越界值不会报错，但 Arcade 的钳制发生在【下一帧】的物理步进：越界位置会先被真的渲染
// 一帧，下一帧才弹回来 —— 隔帧跳变就是墙角抖动的波形（实测 49.4↔42.1↔49.4↔45.75）。
// 曾经这几处各写各的 56，比真实边界内缩 6.6px，既不准也压不住上面那个坑。
BT.EDGE_X = BT.BODY_HALF_W;

// 击退"退得动吗"的判据：上挑滞空约 140ms（vy 90~105 / GRAVITY 1500），其间横向本该
// 走 155×0.14 ≈ 22px。剩余可退空间不足这个数，那一跳就是纯原地的（见 _knockback）。
BT.WALL_ROOM = 26;

// ─────────── 背景三层贴图定位 ───────────
// 三张源图（1920×1080）的地面线【互不相同】，提示词里要求的统一 88% 一个都没遵守：
//   far  地板线      y=703 (65.1%)
//   mid  柱础底      y=894 (82.8%)
//   fore 中央木板顶边 y=769 (71.2%)
// 所以不能用同一个缩放对齐三层，每层单独定标：scale = 目标屏幕 y ÷ 源图 y。
//   far  703 × 0.677 = 475.9 → 地板线正好压在 FLOOR_Y
//   mid  894 × 0.532 = 475.6 → 柱础坐在 FLOOR_Y
//   fore 769 × 0.606 = 466.0 → 木板顶边在 FLOOR_Y 上方 10px：盖住脚踝以下与倒地
//        接触点（配合 BT.DOWN_DROP 的下沉），但只吃 10px，不影响看步法
// 三层都是 origin(0.5,0)、贴画布顶、水平居中，超出 960×540 的部分自然裁掉。
//
// ⚠️ mid 的 0.532 小于 far 的 0.677，中景柱子比远景天花板梁小约 21%——透视上是反的。
// 取舍：统一到 0.677 得把 mid 上移 129px，会削掉顶部灯笼一半，那是更显眼的瑕疵。
// 柱子和天花板梁是不同物体，没有可比的参照，实际观感吃得下。
//
// ─────────── 一场一景 ───────────
// 擂台共两场（oppQueue = 另两家流派），每场一套三层背景：
//   第 1 场 dojo    — 室内道场（原设计，保留）
//   第 2 场 outdoor — 雪山之巅露天演武场：远景雪山 / 中景室外道场檐廊 / 近景枫树银杏
// 落叶前景物理层（foregroundPhysics.js）是独立于背景的运行时系统，两场都在，
// 只是室外那场把它开满——枫/橡/银杏三色本来就是照着 outdoor_fore 的树配的。
BT.BG_SETS = {
  dojo: [
    { key: 'far', scale: 0.677, depth: -100 },
    { key: 'mid', scale: 0.532, depth: -50 },
    { key: 'fore', scale: 0.606, depth: 20 },   // depth > 角色的 10，压在脚上
  ],
  // scale 由 tools/measure-bg.mjs 实测地面线后回填（源图 1920×1080）：
  //   far  石台面中部 y≈891 × 0.534 = 475.8 → 角色站在石台面上，不是台沿外
  //        （最强水平边量到的 856 是台面【后沿】，站那儿等于贴着远景山脚，太靠后）
  //   fore 落叶带中央顶边 y≈860 × 0.542 = 466.1 → FLOOR_Y 上方 10px，同室内套件的接地量
  //   mid  檐廊石阶/栅栏底 y≈887 × 0.537 = 476.3 → 坐在 FLOOR_Y
  //        （中央 60% 量到的 990 是右侧栅栏越界的一小段，中景中央本就留空，取全幅中位）
  // 三层 0.534/0.537/0.542 几乎同比例——这套图彼此协调，不像室内那套 mid 比 far 小 21%
  //
  // ⚠️ outdoor_fore 的 scaleX 是【必需】的，不是调味。前景那两棵树的树干在源图里
  //    各占最外 12%，按 0.542 等比铺开后覆盖屏幕 x∈[-40,85] 与 [875,1000]——
  //    而角色能走到 x≈50（世界边界 0~960，半宽 ~50），被逼到边角时整个人躲进树干
  //    后面看不见了（fore depth 20 > 角色 10）。横向单独拉到 0.62 把树干推出画面，
  //    只留内侧轮廓和垂进来的枝叶当画框；纵向仍按地面线定标，不受影响。
  outdoor: [
    { key: 'outdoor_far', scale: 0.534, depth: -100 },
    { key: 'outdoor_mid', scale: 0.537, depth: -50 },
    // 动态枝叶层：14 帧序列帧循环（tools/build-fore-anim.mjs 从绿幕视频构建）。
    // 目标几何已经【烘进图里】（1012×569，落叶带顶边正好落在 FLOOR_Y−10），所以
    // scale=1、也不再需要 scaleX —— 树干天然裁到画布边外，不会再罩住墙角的角色。
    // animFps 压到 6：14 帧 ÷ 6 = 2.33 秒一轮。保留了中央飘叶（用户定），飘叶位置
    // 让循环做不到真无缝，周期拉长到 2 秒以上那一次跳位才不显眼。
    { key: 'outdoor_fore', animFrames: 14, animFps: 6, scale: 1, depth: 20 },
  ],
};
// 按场次取景（round 从 0 起）。缺图时 _buildStage 会跳过该层，不会 404。
